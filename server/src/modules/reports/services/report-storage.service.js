import crypto from 'node:crypto';

import { cloudinary, isCloudinaryConfigured } from '../../../config/cloudinary.js';
import { AppError } from '../../../middlewares/error.middleware.js';
import { logger } from '../../../config/logger.js';
import env from '../../../config/env.js';

/**
 * BET-12.4/12.5/12.31 — Secure File Upload + Medical File Privacy +
 * Secure Report Downloads.
 *
 * Every report file is uploaded with `type: 'authenticated'` /
 * `access_mode: 'authenticated'` — Cloudinary never serves it from a
 * plain public delivery URL. The only way to read the bytes back out
 * is `getReportFileBuffer()`, which mints a short-lived signed URL
 * server-side and fetches it immediately — the signed URL itself is
 * never returned to the client (master prompt: "avoid predictable
 * URLs", "avoid permanent public links"). `report.service.js#downloadReport`
 * streams the resulting buffer to the client after its own
 * authorization + audit-log check, so every download re-runs
 * authorization rather than reusing a cached link.
 */

export const computeFileHash = (buffer) => crypto.createHash('sha256').update(buffer).digest('hex');

const resourceTypeFor = (mimeType) => {
  // Cloudinary treats anything that isn't an image/video as 'raw'.
  if (mimeType.startsWith('image/')) return 'image';
  return 'raw';
};

/**
 * @param {Buffer} buffer
 * @param {string} storageFilename generated by security/file-security.js — never the original filename
 * @param {string} mimeType
 * @param {string} patientProfileId used only to namespace the storage folder, never exposed to the client
 */
export const uploadReportFile = async ({ buffer, storageFilename, mimeType, patientProfileId }) => {
  if (!isCloudinaryConfigured) {
    throw new AppError('File storage is not configured on this server.', 503, {
      code: 'STORAGE_NOT_CONFIGURED',
    });
  }

  const resourceType = resourceTypeFor(mimeType);
  const publicId = `ash-shafi/reports/${patientProfileId}/${storageFilename}`;

  const result = await new Promise((resolve, reject) => {
    const uploadStream = cloudinary.uploader.upload_stream(
      {
        public_id: publicId,
        resource_type: resourceType,
        type: 'authenticated',
        access_mode: 'authenticated',
        overwrite: false,
        unique_filename: false,
      },
      (error, uploadResult) => (error ? reject(error) : resolve(uploadResult)),
    );
    uploadStream.end(buffer);
  });

  return {
    cloudinaryPublicId: result.public_id,
    cloudinaryResourceType: result.resource_type,
  };
};

/**
 * Mints a short-lived signed URL and immediately fetches the bytes
 * server-side — the URL itself never leaves this function.
 */
export const getReportFileBuffer = async ({ cloudinaryPublicId, cloudinaryResourceType }) => {
  if (!isCloudinaryConfigured) {
    throw new AppError('File storage is not configured on this server.', 503, {
      code: 'STORAGE_NOT_CONFIGURED',
    });
  }

  const expiresAt = Math.floor(Date.now() / 1000) + (env.reports.downloadUrlExpiresSeconds || 120);

  const signedUrl = cloudinary.utils.private_download_url(cloudinaryPublicId, undefined, {
    resource_type: cloudinaryResourceType,
    type: 'authenticated',
    expires_at: expiresAt,
  });

  const response = await fetch(signedUrl);

  if (!response.ok) {
    logger.error(
      { status: response.status, cloudinaryPublicId },
      'Failed to fetch report file from storage.',
    );
    throw new AppError('Unable to retrieve the stored file.', 502, { code: 'STORAGE_FETCH_FAILED' });
  }

  const arrayBuffer = await response.arrayBuffer();
  return Buffer.from(arrayBuffer);
};

export const deleteReportFile = async ({ cloudinaryPublicId, cloudinaryResourceType }) => {
  if (!isCloudinaryConfigured) return;
  try {
    await cloudinary.uploader.destroy(cloudinaryPublicId, {
      resource_type: cloudinaryResourceType,
      type: 'authenticated',
    });
  } catch (error) {
    // Never block a request on storage cleanup failure — log and
    // move on, same fail-safe convention as the access-log writers.
    logger.error({ err: error, cloudinaryPublicId }, 'Failed to delete report file from storage.');
  }
};
