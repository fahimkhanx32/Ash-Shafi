import { cloudinary, isCloudinaryConfigured } from '../../../config/cloudinary.js';
import { AppError } from '../../../middlewares/error.middleware.js';
import { logger } from '../../../config/logger.js';
import env from '../../../config/env.js';

/**
 * BET-13 — Secure Voice Attachments + Message Attachments (master
 * prompt §26/§29/§31).
 *
 * Directly reuses BET-12's `report-storage.service.js` design: every
 * attachment (image/document/voice) is uploaded with
 * `type: 'authenticated'` / `access_mode: 'authenticated'` —
 * Cloudinary never serves it from a plain public delivery URL. The
 * only way to read the bytes back out is `getMessageAttachmentBuffer()`,
 * which mints a short-lived signed URL server-side and fetches it
 * immediately; the signed URL itself is never returned to the client.
 * `message.controller.js#downloadMessageAttachmentController` streams
 * the resulting buffer after `conversation-access.service.js` has
 * already authorized the request.
 *
 * One difference from `report-storage.service.js`: reports are never
 * audio/video, so that module only ever distinguishes 'image' vs.
 * 'raw'. Voice messages are audio, so `resourceTypeFor` here also
 * maps audio (and video, for forward-compatibility with BET-14) to
 * Cloudinary's `'video'` resource type — Cloudinary handles all
 * audio/video delivery through that pipeline regardless of the
 * source being audio-only.
 */

const resourceTypeFor = (mimeType) => {
  if (mimeType.startsWith('image/')) return 'image';
  if (mimeType.startsWith('audio/') || mimeType.startsWith('video/')) return 'video';
  return 'raw';
};

/**
 * @param {Buffer} buffer
 * @param {string} storageFilename generated by security/file-security.js — never the original filename
 * @param {string} mimeType
 * @param {string} conversationId used only to namespace the storage folder, never exposed to the client
 */
export const uploadMessageAttachment = async ({
  buffer,
  storageFilename,
  mimeType,
  conversationId,
}) => {
  if (!isCloudinaryConfigured) {
    throw new AppError('File storage is not configured on this server.', 503, {
      code: 'STORAGE_NOT_CONFIGURED',
    });
  }

  const resourceType = resourceTypeFor(mimeType);
  const publicId = `ash-shafi/messaging/${conversationId}/${storageFilename}`;

  const result = await new Promise((resolve, reject) => {
    const uploadStream = cloudinary.uploader.upload_stream(
      {
        public_id: publicId,
        resource_type: resourceType,
        type: 'authenticated',
        access_mode: 'authenticated',
        overwrite: false,
        unique_filename: false,
      },
      (error, uploadResult) => (error ? reject(error) : resolve(uploadResult)),
    );
    uploadStream.end(buffer);
  });

  return {
    cloudinaryPublicId: result.public_id,
    cloudinaryResourceType: result.resource_type,
  };
};

/**
 * Mints a short-lived signed URL and immediately fetches the bytes
 * server-side — the URL itself never leaves this function.
 */
export const getMessageAttachmentBuffer = async ({
  cloudinaryPublicId,
  cloudinaryResourceType,
}) => {
  if (!isCloudinaryConfigured) {
    throw new AppError('File storage is not configured on this server.', 503, {
      code: 'STORAGE_NOT_CONFIGURED',
    });
  }

  const expiresAt =
    Math.floor(Date.now() / 1000) +
    (env.messaging.attachmentDownloadUrlExpiresSeconds || 120);

  const signedUrl = cloudinary.utils.private_download_url(cloudinaryPublicId, undefined, {
    resource_type: cloudinaryResourceType,
    type: 'authenticated',
    expires_at: expiresAt,
  });

  const response = await fetch(signedUrl);

  if (!response.ok) {
    logger.error(
      { status: response.status, cloudinaryPublicId },
      'Failed to fetch message attachment from storage.',
    );
    throw new AppError('Unable to retrieve the stored file.', 502, {
      code: 'STORAGE_FETCH_FAILED',
    });
  }

  const arrayBuffer = await response.arrayBuffer();
  return Buffer.from(arrayBuffer);
};

export const deleteMessageAttachment = async ({
  cloudinaryPublicId,
  cloudinaryResourceType,
}) => {
  if (!isCloudinaryConfigured || !cloudinaryPublicId) return;
  try {
    await cloudinary.uploader.destroy(cloudinaryPublicId, {
      resource_type: cloudinaryResourceType,
      type: 'authenticated',
    });
  } catch (error) {
    // Never block a request on storage cleanup failure — log and
    // move on, same fail-safe convention as
    // `report-storage.service.js#deleteReportFile`.
    logger.error(
      { err: error, cloudinaryPublicId },
      'Failed to delete message attachment from storage.',
    );
  }
};
